/** Язык интерфейса. [SYSTEM] — русский на русском устройстве, иначе английский (как на Android). */
enum class AppLanguage {
    SYSTEM,
    RUSSIAN,
    ENGLISH;

    /** Язык, которым реально говорит приложение: "ru" или "en". */
    fun resolve(system: String): String = when (this) {
        SYSTEM -> if (system == "ru") "ru" else "en"
        RUSSIAN -> "ru"
        ENGLISH -> "en"
    }

    companion object {
        fun parse(value: String?): AppLanguage = entries.firstOrNull { it.name == value } ?: SYSTEM
    }
}

/**
 * Выбранный язык. Хранится только на этом устройстве, как и тема.
 * Состояние снапшотное: всё, что прочитало [strings] в композиции, перерисуется при смене языка без перезапуска.
 */
object LanguageStore {
    private const val KEY = "language"

    var language by mutableStateOf(AppLanguage.parse(LocalSettings.getString(KEY)))
        private set

    /** "ru" или "en" — для строк и форматтеров дат. */
    val code: String get() = language.resolve(systemLanguageCode)

    fun set(language: AppLanguage) {
        this.language = language
        LocalSettings.putString(KEY, language.name)
    }
}

/** Строки текущего языка. */
val strings: Strings get() = if (LanguageStore.code == "ru") RuStrings else EnStrings

