/** «1 участник», «3 участника», «5 участников». */
private fun ruMembers(count: Int): String {
    val word = when {
        count % 100 in 11..14 -> "участников"
        count % 10 == 1 -> "участник"
        count % 10 in 2..4 -> "участника"
        else -> "участников"
    }
    return "$count $word"
}

